def add_header(doc, title, subtitle):
    doc.add_paragraph("ESTUDIO JURÍDICO ZÚÑIGA").runs[0].bold = True
    doc.add_paragraph(subtitle)
    p = doc.add_paragraph()
    r = p.add_run(title)
    r.bold = True
    doc.add_paragraph("_" * 78)

def save(doc, name):
    doc.save(base / name)
    print(name)

